        public static IEnumerable<(string Name, string Category)> Search(string query, int limit = 20)
        {
            if (string.IsNullOrWhiteSpace(query))
                return All.Take(limit);

            string q = query.Trim();
            return All
                .Where(j => j.Name.Contains(q, StringComparison.OrdinalIgnoreCase)
                         || j.Category.Contains(q, StringComparison.OrdinalIgnoreCase))
                .Take(limit);
        }
