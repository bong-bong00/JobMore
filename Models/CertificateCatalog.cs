        /// <summary>검색어로 필터 (이름·기관 부분일치). 빈 검색어면 상위 일부만.</summary>
        public static IEnumerable<(string Name, string Issuer)> Search(string query, int limit = 20)
        {
            if (string.IsNullOrWhiteSpace(query))
                return All.Take(limit);

            string q = query.Trim();
            return All
                .Where(c => c.Name.Contains(q, StringComparison.OrdinalIgnoreCase)
                         || c.Issuer.Contains(q, StringComparison.OrdinalIgnoreCase))
                .Take(limit);
        }
